const fs=require('fs'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync(require('path').join(__dirname,'../app/src/main/assets/index.html'),'utf8');
const code=html.match(/<script>([\s\S]*?)<\/script>/)[1].replace(/init\(\);\s*$/, '');
const ctx={window:{},document:{addEventListener(){},createElement(){return {style:{},remove(){}}},body:{appendChild(){}},querySelector(){return {innerHTML:""}},querySelectorAll(){return []},getElementById(){return null}},localStorage:{getItem(){return null},setItem(){}},console,Date,JSON,Math,Number,String,setTimeout(){},clearTimeout(){},navigator:{},confirm(){return true},alert(){},Intl};
ctx.window=ctx;vm.createContext(ctx);vm.runInContext(code,ctx);
const get=code=>vm.runInContext(code,ctx);
let settings=get('renderSettings()');
assert(settings.includes('Режимы анализа'),'settings card');
assert(settings.includes('gfToggleEngine'),'toggle');
assert(settings.includes('1. Медицинские правила'));
assert(settings.includes('Облачный ИИ (Mistral / Cloudflare)'));
let home=get('renderHome()');
assert(home.includes('Длинный инсулин'));
assert(home.includes('Записать активность'));
let stats=get('renderStats()');
assert(stats.includes('Медицинский модуль'));
const now=Date.now();
vm.runInContext(`app.readings=[{ts:${now-120000},mmol:6.8,direction:'Flat'},{ts:${now-300000},mmol:6.9,direction:'Flat'}];app.events=[{type:'insulin',insulinType:'short',ts:${now-2*60*60000},units:2},{type:'insulin',insulinType:'short',ts:${now-60*60000},units:1}]`,ctx);
const summary=get('GFMedical.summary({readings:app.readings,events:app.events})');
assert(summary.overlap.hasRecentMultiple,'overlap');
assert(summary.quality.dataFresh,'fresh');
